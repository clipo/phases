def test_calibration_selects_the_largest_difference_among_those_that_fit(tmp_path):
    """The selection rule itself. Selecting the smallest instead would pass every other test here."""
    data = _made_by_the_model(tmp_path, 1.0)
    c = cp.calibrate(data, n_ind=(500,), innovations=(0.0005, 0.004, 0.05), mixings=(0.02, 0.4), reps=3,
                     confirm_reps=12, length=12.0)
    t = c["table"]
    ok = t[t.confirmed]
    assert len(ok) >= 2, "the rule needs at least two fitting settings to be tested"
    assert t[t.selected].fst_median.iloc[0] == ok.fst_median.max() > ok.fst_median.min()
    assert list(c["ranked"].fst_median) == sorted(ok.fst_median, reverse=True)


def test_calibration_reproduces_the_papers_on_its_record():
    """The paper (output/revision_2026_09/calibrated_rates.csv, analysis 47): 51 of 297 combinations
    matched, 48 confirmed, and 2,000 learners, innovation 0.001, mixing 0.02 selected by the difference
    between two spatial clusters. The clusters are rebuilt here as the paper built them."""
    import os

    from mls_emergence.signatures.assortativity import _kmeans_labels
    data = pc.read_table(EXAMPLE, distance=RIVER, order_col="seriation_order")
    xy = np.column_stack([data.lat, data.lon])
    two = _kmeans_labels(xy - xy.mean(0), 2, seed=7)
    c = cp.calibrate(data, length=24.0, select_labels=two, jobs=min(12, os.cpu_count() or 1))
    assert (c["n_matched"], c["n_confirmed"], c["n_cells"]) == (51, 48, 297)
    assert c["rates"] == {"n_ind": 2000, "innovation": 0.001, "mixing": 0.02, "length": 24.0}


def test_runs_that_lose_all_diversity_are_counted_not_dropped(tmp_path):
    """With no innovation a small population fixes on one class. Such runs show no difference between
    phases; leaving them out would keep only the runs that differ and overstate the model."""
    data = _made_by_the_model(tmp_path, 1.0)
    r = cp.compare_with_model(data, {"n_ind": 200, "innovation": 0.0, "mixing": 0.4, "length": 12.0}, reps=60, seed=10)
    f = r["rows"][0]
    assert r["flat"] > 0 and f["runs"] == 60          # every run stays in the count
    assert f["reaching"] <= 60 - r["flat"]            # a flat run cannot reach a positive difference
    with pytest.raises(ValueError, match="lost all diversity"):      # nearly every run flat: refused
        cp.compare_with_model(data, {"n_ind": 40, "innovation": 0.0, "mixing": 0.4, "length": 12.0}, reps=60, seed=10)


def _row(observed, lo, hi, reaching=10, runs=100):
    return {"observed": observed, "lo": lo, "hi": hi, "median": (lo + hi) / 2, "reaching": reaching, "runs": runs}


def test_question_7_is_read_from_both_sides():
    """Each reading must be true of the numbers that trigger it. The first version said the model
    'accounts for' a record that was LESS differentiated than every run."""
    from phasecheck.report import _reading_7
    r = {"n_ind": 1, "innovation": 0, "mixing": 0, "length": 1}
    above = _reading_7([("a", r, _row(0.05, 0.001, 0.02, 0))], True)
    below = _reading_7([("a", r, _row(0.0005, 0.004, 0.02, 100))], True)
    inside = _reading_7([("a", r, _row(0.01, 0.001, 0.02, 30))], True)
    mixed = _reading_7([("a", r, _row(0.01, 0.001, 0.02, 30)), ("b", r, _row(0.01, 0.0001, 0.004, 0))], True)
    assert "differ by more than the model" in above and "does not fit" not in above
    assert "differ by LESS" in below and "does not fit this record" in below and "can produce" not in below
    assert "inside the range" in inside and "can produce a difference of this size" in inside
    assert "depends on the setting" in mixed and "cannot say" in mixed
    # a record no setting shows to exceed the model is not "undecided": the model can account for it
    null = _reading_7([("a", r, _row(0.0003, 0.001, 0.02, 100)), ("b", r, _row(0.0003, 0.0001, 0.004, 40)),
                       ("c", r, _row(0.0003, 0.0001, 0.002, 30))], True)
    assert "At no setting tried" in null and "can produce a difference of this size" in null
    assert "cannot say" not in null and "do not fit it" in null
    supplied = _reading_7([("a", r, _row(0.01, 0.001, 0.02, 30))], False)
    assert "holds only if they fit" in supplied and "holds only if they fit" not in inside


def _pw(free_med, tight_med, free_low, tight_low, distinct_compact=20):
    row = lambda leak, med, low: {"leak": leak, "records": 100, "around": [0, 0, med, 1, 1],
                                  "compact": [0, 0, med, 1, 1], "around_at_or_below": low,
                                  "compact_at_or_below": low, "reach_fst": 0.1}
    return {"rows": [row(1.0, free_med, free_low), row(0.03, tight_med, tight_low)], "n_alt": 50,
            "observed_around": 0.5, "observed_compact": 0.5, "distinct_around": 40,
            "distinct_compact": distinct_compact, "same_as_phases_around": 0, "same_as_phases_compact": 0}


def test_question_9_is_read_from_the_numbers():
    from phasecheck.report import _reading_9, _share
    strong = _reading_9(_pw(0.4, 0.8, 0.7, 0.25))
    assert "strongly" in strong and "responds to a restriction" in strong and "weighs against one" in strong
    weak = _reading_9(_pw(0.5, 0.6, 0.55, 0.40))
    assert "slightly" in weak and "though weakly" in weak and "weighs weakly against one" in weak
    flat = _reading_9(_pw(0.5, 0.4, 0.5, 0.55))
    assert "cannot detect a restriction here" in flat and "responds to" not in flat
    assert "does not favor either" in flat
    for_one = _reading_9(_pw(0.4, 0.8, 0.02, 0.9))
    assert "weighs for one" in for_one and "0.0 to 1" not in for_one and "30.0 times" in for_one
    assert "lower bound" in _reading_9(_pw(0.4, 0.8, 0.6, 0.0))
    # direction: at_or_below of 0 for both means every simulated record scored ABOVE the real one
    lowest = _reading_9(_pw(0.4, 0.8, 0.0, 0.0))
    assert "scored above the real one" in lowest and "lower than either kind" in lowest and "higher than" not in lowest
    from phasecheck.report import _pct
    assert (_pct(1 / 300), _pct(0.0), _pct(0.25), _pct(3 / 1000)) == ("0.3", "0", "25", "0.3")
    assert "carries little weight" in _reading_9(_pw(0.4, 0.8, 0.7, 0.25, distinct_compact=2))
    assert _share(1, 300) == "1 of 300 (0.3%)" and _share(0, 300) == "none of 300" and _share(30, 300) == "30 of 300 (10%)"


def test_tied_order_values_share_a_position_whatever_the_row_order(tmp_path):
    lat, lon, phase = _map()
    df = pd.DataFrame(np.random.default_rng(2).multinomial(200, [.5, .3, .2], size=len(lat)), columns=["a", "b", "c"])
    df.insert(0, "period", np.repeat([1, 2, 3], len(lat) // 3))
    df.insert(0, "phase", phase); df.insert(0, "longitude", lon); df.insert(0, "latitude", lat)
    df.insert(0, "name", [f"s{i}" for i in range(len(df))])
    p1, p2 = tmp_path / "a.csv", tmp_path / "b.csv"
    df.to_csv(p1, index=False); df.iloc[::-1].to_csv(p2, index=False)
    a, b = pc.read_table(p1, order_col="period"), pc.read_table(p2, order_col="period")
    assert len(set(np.round(a.order, 9))) == 3
    assert dict(zip(a.names, a.order)) == dict(zip(b.names, b.order))


