PAPER_RATES = {"n_ind": 2000, "innovation": 0.001, "mixing": 0.02, "length": 24.0}


def test_the_model_is_the_papers_model():
    """Same weights, same frequencies, same sampled counts as the implementation the paper ran."""
    from mls_emergence.transmission import spatial as sp
    rng = np.random.default_rng(0)
    pts = rng.uniform(0, 80, (12, 2))
    d = np.sqrt(((pts[:, None] - pts[None]) ** 2).sum(-1))
    lab, tgt = np.repeat([0, 1, 2], 4), np.array([.5, .3, .15, .05])
    for leak in (1.0, 0.03):
        a, b = md.copying_weights(d, 24.0, lab, leak), sp.copying_weights(d, 24.0, labels=lab, leak=leak)
        ra = md.drift_record(a, k=4, n_ind=500, mixing=.02, innovation=.001, target=tgt, seed=7)
        rb = sp.drift_record(b, k=4, n_ind=500, mixing=.02, innovation=.001, seed=7, target=tgt)
        o, t = np.linspace(0, 1, 12), np.full(12, 200)
        assert np.array_equal(a, b) and np.array_equal(ra, rb)
        assert np.array_equal(md.sample_record(ra, o, t, np.random.default_rng(3)),
                              sp.sample_record(rb, o, t, np.random.default_rng(3)))


def test_a_restriction_lowers_copying_across_lines_only():
    """Direction. leak below 1 must reduce the share of copying that crosses a line, never raise it."""
    d = np.abs(np.subtract.outer(np.arange(6.0), np.arange(6.0))) * 10
    lab = np.repeat([0, 1], 3)
    cross = lambda w: float(w[lab[:, None] != lab[None, :]].sum())
    free, cut = md.copying_weights(d, 20.0, lab, 1.0), md.copying_weights(d, 20.0, lab, 0.03)
    assert cross(cut) < 0.2 * cross(free)
    assert np.allclose(free.sum(1), 1) and np.allclose(cut.sum(1), 1)
    with pytest.raises(ValueError, match="needs labels"):
        md.copying_weights(d, 20.0, None, 0.5)
    with pytest.raises(ValueError, match="positive"):
        md.copying_weights(d, 0.0)


def test_reproduces_the_papers_comparison_with_the_copying_model():
    """Expected values from output/findings/phase_profiles.md and phases_as_groups.md (analyses 99 and
    84), which run the paper's own implementation at the calibrated settings with these seeds."""
    data = pc.read_table(EXAMPLE, distance=RIVER, order_col="seriation_order")
    r = cp.compare_with_model(data, PAPER_RATES, reps=300, seed=84000)
    rows = {x["measure"]: x for x in r["rows"]}
    f = rows["cultural F_ST between the phases"]
    assert (round(f["observed"], 4), round(f["median"], 4), round(f["lo"], 4), round(f["hi"], 4)) == \
        (0.0123, 0.0024, 0.0006, 0.0116) and (f["reaching"], f["runs"]) == (7, 300)
    s = rows["sherds that would have to change class to make two phases alike, mean over pairs (percent)"]
    assert (round(s["observed"], 1), round(s["median"], 1), round(s["lo"], 1), round(s["hi"], 1)) == \
        (19.4, 7.4, 4.0, 13.2) and s["reaching"] == 0
    assert rows["sherds that would have to change class, Kent and Parkin (percent)"]["reaching"] == 17
    e = rows["boundary excess at the phase lines"]
    assert round(e["observed"], 1) == 7.7 and round(e["median"], 1) == 1.2      # both positive
    assert round(r["decay"]["observed"], 2) == -0.20                            # similarity falls with distance
    assert r["decay"]["lo"] < r["decay"]["observed"] < r["decay"]["hi"]


def _map(seed=11, n=24):
    rng = np.random.default_rng(seed)
    east, north = rng.uniform(0, 60, n), rng.uniform(0, 60, n)
    lat, lon = 35.0 + north / 111.32, -90.0 + east / (111.32 * np.cos(np.deg2rad(35.27)))
    phase = np.where(east < 20, "West", np.where(east < 40, "Mid", "East"))
    return lat, lon, phase


def _table(counts, lat, lon, phase, tmp_path, name):
    df = pd.DataFrame(counts, columns=[f"class_{j + 1}" for j in range(counts.shape[1])])
    df.insert(0, "phase", phase); df.insert(0, "longitude", lon); df.insert(0, "latitude", lat)
    df.insert(0, "name", [f"site_{i + 1:02d}" for i in range(len(df))])
    p = tmp_path / name
    df.to_csv(p, index=False)
    return pc.read_table(p)


RATES = {"n_ind": 500, "innovation": 0.004, "mixing": 0.02, "length": 12.0}


def _made_by_the_model(tmp_path, leak, seed=3):
    """A record generated by the copying model itself on a constructed map, with or without a restriction."""
    lat, lon, phase = _map()
    shell = _table(np.full((len(lat), 6), 50), lat, lon, phase, tmp_path, "shell.csv")
    shell.counts = np.random.default_rng(1).multinomial(300, [.35, .25, .18, .12, .06, .04], size=len(lat))
    m = cp.simulate(shell, RATES, seed, leak=leak)
    return _table(m, lat, lon, phase, tmp_path, f"made_{leak}.csv")


def test_model_comparison_tells_a_restricted_record_from_an_unrestricted_one(tmp_path):
    """The discriminating pair for question 7. A record made by the model with no groups must fall
    inside the model's own range; the same map with copying across the lines cut to 3 percent must
    stand above it. A comparison that always found an excess, or never did, fails one half."""
    free = cp.compare_with_model(_made_by_the_model(tmp_path, 1.0), RATES, reps=80, seed=500)["rows"][0]
    cut = cp.compare_with_model(_made_by_the_model(tmp_path, 0.03), RATES, reps=80, seed=500)["rows"][0]
    assert free["reaching"] / free["runs"] > 0.05
    assert cut["reaching"] / cut["runs"] < 0.05 and cut["observed"] > 3 * free["observed"]


def test_power_rises_with_the_restriction(tmp_path):
    """Records made with a restriction must score higher against alternative lines than records made
    without one. Equal scores would mean the comparison cannot detect what it is used to detect."""
    p = cp.power(_made_by_the_model(tmp_path, 1.0), RATES, records=60, n_alt=40, leaks=(1.0, 0.03), seed=900)
    free, cut = p["rows"]
    assert cut["around"][2] > free["around"][2] + 0.2          # medians
    assert 0 <= p["observed_around"] <= 1


def test_calibration_finds_the_settings_that_made_the_record_and_refuses_when_none_fit(tmp_path):
    data = _made_by_the_model(tmp_path, 1.0)
    grid = {"n_ind": (500,), "innovations": (0.0005, 0.004, 0.05), "mixings": (0.02, 0.4), "reps": 3,
            "confirm_reps": 12, "length": 12.0}
    c = cp.calibrate(data, **grid)
    assert c["n_confirmed"] >= 1 and c["rates"]["length"] == 12.0
    sel = c["table"][c["table"].selected].iloc[0]
    obs = cp.diversity(data.counts)
    assert abs(sel.sim_within - obs["within"]) / obs["within"] <= 0.10
    # the settings that made the record are among the confirmed ones
    made = c["table"][(c["table"].innovation == 0.004) & (c["table"].mixing == 0.02)].iloc[0]
    assert bool(made.confirmed)
    with pytest.raises(ValueError, match="no setting of the copying model reproduces"):
        cp.calibrate(data, **{**grid, "tolerance": 1e-6})


def test_order_column_places_assemblages_and_is_not_a_class(tmp_path):
    lat, lon, phase = _map()
    df = pd.DataFrame(np.random.default_rng(2).multinomial(200, [.5, .3, .2], size=len(lat)),
                      columns=["a", "b", "c"])
    df.insert(0, "date_ad", np.linspace(1350, 1550, len(lat))[::-1])
    df.insert(0, "phase", phase); df.insert(0, "longitude", lon); df.insert(0, "latitude", lat)
    df.insert(0, "name", [f"s{i}" for i in range(len(df))])
    p = tmp_path / "o.csv"; df.to_csv(p, index=False)
    data = pc.read_table(p, order_col="date_ad")
    assert data.classes == ["a", "b", "c"]
    assert data.order[0] == 1.0 and data.order[-1] == 0.0       # the latest date is 1, the earliest 0
    assert np.allclose(np.sort(data.order), np.linspace(0, 1, len(lat)))
    with pytest.raises(ValueError):
        pc.read_table(p)                                         # unnamed, the date column is refused


